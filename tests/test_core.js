const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'student-db-'));
process.env.DATABASE_PATH = path.join(temp, 'app.sqlite');
const db = require('../src/db/connection');
const { runMigrations } = require('../src/db/migrate');
runMigrations();
const { seed } = require('../src/db/seed');
const { parseCsv } = require('../src/services/csvParser');
const { importCsvDataset } = require('../src/services/dataset');
const { validateStudentRows } = require('../src/validators/studentSchema');
const fixture = require('../ml/examples/valid_two_rows.json');
const { savePredictionRun } = require('../src/services/predictionRuns');
const { validatePredictionOutput } = require('../src/services/predictionValidator');
test.after(() => { db.close(); fs.rmSync(temp, { recursive: true, force: true }); });
test('migrations and seeding are idempotent, schema constraints enforced', () => {
    runMigrations(); seed(); seed();
    assert.equal(db.get('SELECT COUNT(*) AS n FROM accounts').n, 1);
    assert.equal(db.pragma('foreign_keys', { simple: true }), 1);
    assert.throws(() => db.run("INSERT INTO accounts(id,email,password_hash) VALUES('bad','bad@t.edu','hash')"), /username/);
});
test('CSV preserves quoted content, rejects malformed encoding, quotes and counts', () => {
    assert.equal(parseCsv(Buffer.from('a,b\r\n" x ","line1\nline2"\r\n')).rows[0].a, ' x ');
    assert.equal(parseCsv(Buffer.from('a;b\n"he""llo";2')).rows[0].a, 'he"llo');
    for (const value of ['a,b\n1,2,3', 'a,b\nhe"ll"o,2', 'a,b\n"oops,2', 'a,a\n1,2']) assert.throws(() => parseCsv(Buffer.from(value)));
    assert.throws(() => parseCsv(Buffer.from([0xff, 0xfe, 0xff])), /UTF-8/);
    assert.throws(() => parseCsv(Buffer.alloc(1024 * 1024 + 1)), /1 MiB/);
});
test('31 features strip targets, reject duplicates and cap 50 errors', () => {
    const valid = validateStudentRows(fixture.map(row => ({ ...row, G2: 10, G3: 12 })));
    assert.equal(valid.isValid, true);
    assert.equal(Object.keys(valid.validRows[0]).length, 32); // 31 features plus optional label metadata
    assert.equal('G2' in valid.validRows[0], false);
    assert.equal('G3' in valid.validRows[0], false);
    assert.equal(validateStudentRows(Array.from({ length: 60 }, () => ({ age: 999 }))).errors.length, 50);
    assert.equal(validateStudentRows([{ ...fixture[0], age: ' ' }]).isValid, false);
    assert.equal(validateStudentRows([fixture[0], fixture[0]]).isValid, false);
});
test('atomic upload, run persistence, rollback and cascade', async () => {
    const accountId = db.get("SELECT id FROM accounts WHERE username='admin'").id;
    const headers = Object.keys(fixture[0]);
    const csv = rows => Buffer.from([headers.join(';'), ...rows.map(row => headers.map(key => row[key]).join(';'))].join('\n'));
    const before = db.get('SELECT COUNT(*) AS n FROM datasets').n;
    await assert.rejects(importCsvDataset({ buffer: csv([{ ...fixture[0], G1: -1 }]), filename: 'bad.csv', accountId }));
    assert.equal(db.get('SELECT COUNT(*) AS n FROM datasets').n, before);
    db.exec("CREATE TRIGGER reject_row BEFORE INSERT ON student_rows WHEN NEW.row_index = 2 BEGIN SELECT RAISE(ABORT, 'upload rollback'); END;");
    await assert.rejects(importCsvDataset({ buffer: csv(fixture), filename: 'rollback.csv', accountId }), /upload rollback/);
    assert.equal(db.get('SELECT COUNT(*) AS n FROM datasets').n, before);
    assert.equal(db.get('SELECT COUNT(*) AS n FROM student_rows').n, 0);
    db.exec('DROP TRIGGER reject_row');
    const dataset = await importCsvDataset({ buffer: csv(fixture), filename: 'valid.csv', accountId });
    const stored = db.all('SELECT * FROM student_rows WHERE dataset_id = ? ORDER BY row_index', dataset.id);
    assert.equal(Object.keys(JSON.parse(stored[0].features_json)).length, 31);
    assert.equal(dataset.mean, 10.5);
    const results = stored.map(row => ({ row_id: row.row_identifier, row_identifier: row.row_identifier, student_row_id: row.id, risk_score: 0.49996, risk_flag: 0 }));
    const input = stored.map(row => ({ row_id: row.row_identifier, row_identifier: row.row_identifier, student_row_id: row.id }));
    const output = { success: true, schema_version: 'schema-v1', model_version: 'student_risk_v1', threshold: 0.5, count: results.length, results };
    assert.equal(validatePredictionOutput(output, input), true);
    for (const threshold of [0.8, NaN, Infinity]) assert.throws(() => validatePredictionOutput({ ...output, threshold }, input));
    assert.throws(() => validatePredictionOutput({ ...output, results: [results[0], results[0]] }, input));
    const args = { datasetId: dataset.id, accountId, modelVersion: output.model_version, schemaVersion: output.schema_version, threshold: 0.5, results };
    const id = savePredictionRun(args);
    assert.equal(db.get('SELECT total_records FROM runs WHERE id = ?', id).total_records, 2);
    assert.throws(() => savePredictionRun({ ...args, results: [results[0], results[0]] }));
    assert.equal(db.get('SELECT COUNT(*) AS n FROM runs').n, 1);
    db.exec("CREATE TRIGGER fail_second BEFORE INSERT ON prediction_results WHEN NEW.student_row_id = '" + stored[1].id + "' BEGIN SELECT RAISE(ABORT, 'forced rollback'); END;");
    assert.throws(() => savePredictionRun(args), /forced rollback/);
    assert.equal(db.get('SELECT COUNT(*) AS n FROM runs').n, 1);
    db.exec('DROP TRIGGER fail_second');
    db.run('DELETE FROM accounts WHERE id = ?', accountId);
    assert.equal(db.get('SELECT COUNT(*) AS n FROM prediction_results').n, 0);
});
